#include "../include/StatusReporterThread.h"
#include "../include/MainWindow.h"

StatusReporterThread::StatusReporterThread(QThread *parentThread)
    : m_parentThread(parentThread) {}


void StatusReporterThread::run() {
    int i = 1;
    if(m_parentThread){
        while (! m_parentThread->isRunning() && (!m_abort)){
            //std::cout << "Debug: Waiting"<<std::endl;
        }
        while (m_parentThread->isRunning() && (!m_abort)) {
            std::this_thread::sleep_for(std::chrono::seconds(1));
            emit(StatusChanged(i));
            i++;
        }
        if (!m_parentThread->isRunning()) {
            emit(StatusChanged(0));
        }
        else if(m_abort){
            emit(StatusChanged(-1));
        }
    }
    
    else{
        emit(StatusChanged(0));
    }
    
}

void StatusReporterThread::KillNow(){
    m_abort = true;
}

bool StatusReporterThread::Killing(){
    return m_abort;
}

StatusReporterThread::~StatusReporterThread() {}