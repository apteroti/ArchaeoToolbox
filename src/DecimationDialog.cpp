// DecimationDialog.cpp
#include "DecimationDialog.h"

DecimationDialog::DecimationDialog(QWidget *parent)
    : QDialog(parent)
{
    setWindowTitle("Mesh Decimation");

    QLabel *label = new QLabel("Do you want to decimate the mesh? \n This might take a long time.", this);

    percentageCombo = new QComboBox(this);
    percentageCombo->addItems({"25%", "50%", "75%", "95%"});
    percentageCombo->setCurrentText("25%");

    yesButton = new QPushButton("Yes", this);
    noButton = new QPushButton("No", this);

    connect(yesButton, &QPushButton::clicked, this, &DecimationDialog::onYesClicked);
    connect(noButton, &QPushButton::clicked, this, &QDialog::reject);

    QHBoxLayout *buttonLayout = new QHBoxLayout;
    buttonLayout->addWidget(yesButton);
    buttonLayout->addWidget(percentageCombo);
    buttonLayout->addWidget(noButton);

    QVBoxLayout *mainLayout = new QVBoxLayout(this);
    mainLayout->addWidget(label);
    mainLayout->addLayout(buttonLayout);

    setLayout(mainLayout);
}

void DecimationDialog::onYesClicked() {
    QString text = percentageCombo->currentText();
    text.chop(1);  // Remove last character (the '%')
    percentage = text.toInt();
    accept(); // Close dialog with Accepted status
}

int DecimationDialog::GetSelectedPercentage() const {
    return percentage;
}
